/**
 * Deterministic transition function for Scenario 2
 * Source of Truth: research/scenarios/scenario-2.md
 */
export function getNextNodeS2(
  currentNodeId: NodeIdS2,
  classification?: Classification | null
): NodeIdS2 | null {
  switch (currentNodeId) {
    case "N1":
      switch (classification) {
        case "advanced":
          return "N2";
        case "medium":
          return "N1_H";
        case "weak":
        default:
          return "N1_F";
      }

    case "N1_H":
      switch (classification) {
        case "advanced":
        case "medium":
          return "N2";
        case "weak":
        default:
          return "N1_F";
      }

    case "N1_F":
      // Rescue fallback always advances to N2
      return "N2";

    case "N2":
      // All N2 responses converge forward to N3; feedback carries depth
      return "N3";

    case "N2_H":
      return "N3";

    case "N3":
      switch (classification) {
        case "advanced":
        case "medium":
          return "N4";
        case "weak":
        default:
          return "N2_H";
      }

    case "N3_H":
      return "N4";

    case "N4":
      // Rebuilt idea always advances to N5
      return "N5";

    case "N4_H":
      return "N5";

    case "N5":
      switch (classification) {
        case "advanced":
        case "medium":
          return "END";
        case "weak":
        default:
          return "N4_H";
      }

    case "N5_H":
      return "END";

    case "END":
      return null;

    default:
      return null;
  }
}

export function getScenario2Node(nodeId: string): Scenario2Node {
  const safeId = (nodeId in SCENARIO_2_NODES ? nodeId : "N1") as NodeIdS2;
  return SCENARIO_2_NODES[safeId];
}